public class Train
{
    private String  trainNumber;
    private int     seats;
    private boolean first;
    
    public void setTrainNumber(String neuTrainNumber)
    {
        trainNumber = neuTrainNumber;
    }
    
    
    public String getTrainNumber()
    {
        return trainNumber;
    }
    
    public int getSeats()
    {
        return seats;
    }
    
    public boolean getFirst()
    {
        return first;
    }    
}